// σπήλαια με ακανόνιστα τοιχώματα, ποτάμια, γέφυρες και αίθουσες — ανοιχτοί χώροι, ποτέ λαβύρινθος.
//
// Χάρτης: # = βράχος / λίθοι   . = δάπεδο   ~ = νερό (στο VIII: λάβα)   : = χάσμα   S = αφετηρία (μόνο στο I)
//         (νερό και χάσμα: δεν περπατιούνται, αλλά ο ήχος περνάει από πάνω τους)
