//         E = η τελική έξοδος (μόνο στο XII)   B = ο Κέρβερος (X — στάδιο 5)
//         o = οβολός   s = χορδή της λύρας   j = αγγείο σπονδής   L = πήλινη πινακίδα (STORY.tablets, με τη σειρά)
//         1..9 = μήνυμα χαμένης ψυχής (STORY.souls[n-1])
