function artScareDog(g, m) {
  // Κεφάλι σκύλου από μπροστά, που γρυλίζει: αυτιά, κόκκινα μάτια, ρυτιδιασμένη μουσούδα, σαγόνι που ανοίγει.
  const F = 'ink2/mar4';
  g.sym(50, (x) => {
    g.blob([[x(22), 36], [x(14), 4, 1], [x(36), 26]], F, { size: 12 });                 // αυτί
    g.blob([[x(22), 34], [x(18), 14], [x(30), 28]], 'mar3', { flat: true });
  });
  const hd = [[16, 56], [20, 34], [34, 22], [50, 20], [66, 22], [80, 34], [84, 56], [78, 74], [64, 80], [36, 80], [22, 74]];
  g.blob(hd, F, { size: 50 });
  g.hatch(g.path(hd), 'mar3', 22, (i, r) => { const x = 20 + r() * 60, y = 26 + r() * 40; return [[x, y], [x + (x < 50 ? -3 : 3), y + 5]]; }, 1, 6);
  g.sym(50, (x) => {
    g.line([[x(28), 40], [x(38), 44], [x(45), 41]], 2.4, 'ink0', {});
    g.blob([[x(31), 48], [x(36), 44], [x(43), 46], [x(41), 51], [x(34), 52]], 'ink0', { flat: true });
    g.dot(x(37.5), 48, 2.4, 'red4'); g.px(x(37.5), 47.6, 'cla5', 2);
    g.mark(x(37.5), 48);
  });
  // Μουσούδα και ρυτίδες.
  const o = m === 0 ? 0 : m === 1 ? 8 : 18;
  g.blob([[34, 58], [40, 52], [60, 52], [66, 58], [64, 70], [36, 70]], F, { size: 20 });
  for (const s of [-1, 1]) for (let k = 0; k < 3; k++) g.line([[50 + s * (5 + k * 3), 54 + k * 2], [50 + s * (9 + k * 3), 58 + k * 2]], 1.2, 'ink0', { px: true });
  g.blob([[44, 54], [56, 54], [54, 60], [46, 60]], 'ink0/ink2', { size: 5 });
  if (o) {
    g.blob([[34, 70], [66, 70], [62, 70 + o], [38, 70 + o]], 'red2/red4', { size: 10 });
    g.limb([[50, 72 + o * 0.4], [50, 68 + o]], 7, 5, 'red4', { size: 4 });   // γλώσσα
    g.blob([[34, 70 + o], [66, 70 + o], [62, 80 + o], [38, 80 + o]], F, { size: 10 });
  }
  for (let i = 0; i < 10; i++) {
    const x = 36 + i * 3.1, L = i === 0 || i === 9 ? 7 : 3;
    g.poly([[x - 1.3, 69], [x + 1.3, 69], [x, 69 + L]], 'crm5', { flat: true });
    if (o) g.poly([[x - 1.3, 71 + o], [x + 1.3, 71 + o], [x, 71 + o - L]], 'crm4', { flat: true });
  }
}
// Χέρι που ανεβαίνει από κάτω: σκελετωμένο (σκιά), με νύχια (Ερινύα), πατούσα (Κέρβερος). Σχέδιο 40 × 70.
function artScareHand(g, kind) {
  if (kind === 'cerberus') {
    g.limb([[20, 70], [20, 34]], 22, 18, 'ink2/mar4', { size: 14 });
    g.blob([[6, 36], [8, 22], [20, 18], [32, 22], [34, 36], [20, 40]], 'ink2/mar4', { size: 16 });
    for (let k = 0; k < 4; k++) g.poly([[10 + k * 6.6, 21], [12.6 + k * 6.6, 21], [11 + k * 6.6, 6 + (k % 3)]], 'crm4', { size: 3 });
    return;
  }
  const T = kind === 'erinys' ? 'brn4/brn6' : 'brn2/brn4';
  g.limb([[20, 70], [20, 40]], kind === 'erinys' ? 11 : 9, 8, kind === 'erinys' ? T : 'ink2/ink4', { size: 8 });
  g.blob([[12, 42], [14, 32], [26, 32], [28, 42], [20, 46]], T, { size: 10 });
  for (let k = 0; k < 4; k++) {
    const x = 13 + k * 4.6;
    g.limb([[x, 33], [x - 2 + k, 20], [x - 4 + k * 1.6, 9]], [3, 2.4, 1.6], 0, T, { size: 2 });
    g.poly([[x - 5 + k * 1.6, 10], [x - 3 + k * 1.6, 10], [x - 4.5 + k * 1.6, 2]], 'crm4', { flat: true });
  }
  g.limb([[27, 38], [34, 30], [36, 22]], [3.2, 2.6, 1.8], 0, T, { size: 2 });
}
// Φτερό νυχτερίδας (αριστερό): κόκαλα-δάχτυλα και μεμβράνη. Σχέδιο 80 × 70.
function artScareWing(g) {
  const sh = [76, 50], el = [50, 14];
  const tips = [[4, 4], [0, 30], [8, 54], [28, 66]];
  const mem = [sh, el];
  tips.forEach((t, i) => { const n = tips[i + 1] || [60, 62]; mem.push([t[0], t[1], 1], [(t[0] + n[0]) / 2 + 5, (t[1] + n[1]) / 2 - 3]); });
  mem.push([60, 62]);
  g.blob(mem, 'mar1/mar3', { size: 30 });
  g.limb([sh, el], 6, 4.4, 'ink2/mar4', { size: 4 });
  for (const t of tips) g.limb([el, t], 3.4, 1.2, 'ink2/mar4', { size: 3 });
}

// Όλα μαζί, στη μορφή που περιμένει το Scare.build: faces[στόμα][καρέ], eyes, hand, wing.
Art.scareKinds = function () {
  const pk = (name, w, h, ph, fn, frames) => this.paint(name, w, h, ph, fn, { frames, dither: 0.3 });
  const faces = (name, fn, frames = 1) => [0, 1, 2].map((m) => pk(name + m, 100, 120, 140, (g, f) => fn(g, m, f), frames));
  const out = {};
  out.shade = { faces: faces('_scShade', artScareShade), hand: pk('_scHandS', 40, 70, 80, (g) => artScareHand(g, 'shade'))[0] };
  out.erinys = { faces: faces('_scErinys', artScareErinys, 2), hand: pk('_scHandE', 40, 70, 80, (g) => artScareHand(g, 'erinys'))[0], wing: pk('_scWing', 80, 70, 80, artScareWing)[0] };
  out.cerberus = { faces: faces('_scDog', artScareDog), hand: pk('_scPaw', 40, 70, 80, (g) => artScareHand(g, 'cerberus'))[0] };
  for (const k in out) out[k].eyes = out[k].faces[0][0].eyes || [];
  return out;
};
