// Τα κομμάτια της μουσικής (Sound.setMusic / Sound.musicTick, js/sound.js). Κάθε κομμάτι παίζει σε "μέτρα":
// len = δευτ. ανά μέτρο, vol = ένταση, pad = οι τόνοι του χαλιού (ημιτόνια από το Ρε4), bar(S, t, i, out) =
// προγραμματίζει τις νότες του μέτρου i από τη στιγμή t στο out. Όλα στη λύρα (Karplus-Strong), σε τρόπους της
// αρχαίας μουσικής: Ρε δώριος / αιολικός για τα ήρεμα, φρύγιος για τον κίνδυνο, Ρε μείζονα για το καλό τέλος.

const MUS_D4 = 293.66;
const musNote = (S, st, t, v, out) => S.pluck(MUS_D4 * Math.pow(2, st / 12), t, v, { dest: out });

// Αρπίσιμο μιας συγχορδίας: μπάσο, και οι νότες της από πάνω σε δοσμένα σημεία του μέτρου.
function musArp(S, t, out, chord, times, v, oct = 12) {
  musNote(S, chord[0] - 12, t, v * 1.25, out);
  const seq = [...chord, chord[0] + 12, ...chord.slice(1).reverse()];
  times.forEach((dt, k) => musNote(S, seq[k % seq.length] + oct - 12, t + dt, v * (k % 2 ? 0.8 : 1), out));
}

