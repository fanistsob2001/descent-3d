'use strict';

// Οι μορφές του 3D κόσμου σε μεγάλη λεπτομέρεια (στο στυλ των εικόνων αναφοράς του χρήστη):
// "ζωγραφισμένες" με το paintGrid (ελλείψεις, γραμμές, πολύγωνα πάνω σε πλέγμα χαρακτήρων της
// SPR_PAL), περίπου στο διπλάσιο μέγεθος των παλιών sprites. Μετά το Sprites.getHD τις περνάει
// από Scale2x + σκίαση. Στον κόσμο μπαίνουν με scale ≈ 0.5 (είναι 2× πιο λεπτομερείς).
// Οι cutscenes και η κάτοψη κρατάνε τα παλιά, μικρά sprites.
// Όλες κοιτάνε δεξιά (εκτός από όσες είναι από μπροστά: Ερινύα, Άδης, Περσεφόνη).

const Creatures = {
  init() {
    const F = Sprites.frames;
    const dk = '20,10,6';
    F.erinys3d = [0, 1].map((f) => Sprites.build(this.erinys(f), POT.terra));
    F.charon3d = [0, 1].map((f) => Sprites.build(this.charon(f), dk));
    F.boat3d = [Sprites.build(this.boat(), dk)];
    F.hades3d = [Sprites.build(this.hades(), dk)];
    F.persephone3d = [0, 1].map((f) => Sprites.build(this.persephone(f), dk));
    F.eurydice3d = [0, 1, 2].map((f) => Sprites.build(this.eurydice(f), '150,140,128'));
    F.soulM3d = [0, 1].map((f) => Sprites.build(this.soul('m', f), '150,140,128'));
    F.soulF3d = [0, 1].map((f) => Sprites.build(this.soul('f', f), '150,140,128'));
    F.soulOld3d = [0, 1].map((f) => Sprites.build(this.soul('old', f), '150,140,128'));
    F.snake3d = [0, 1].map((f) => Sprites.build(this.snake(f), dk));
  },

  // ---- Ερινύα: φτερωτή γυναίκα από μπροστά (σαν σειρήνα), φίδια στα μαλλιά, κίτρινα μάτια,
  // νύχια, κουρελιασμένο μαύρο ρούχο. f = 0: φτερά πάνω, 1: φτερά κάτω.
  erinys(f) {
    return paintGrid(36, 42, (p) => {
      // Φτερά (αριστερό, μετά καθρέφτισμα): μεμβράνη σκούρου κόκκινου με μαύρα κόκαλα.
      const tips = f ? [[1, 15], [0, 25], [4, 32], [9, 30]] : [[2, 1], [0, 9], [1, 18], [7, 22]];
      p.poly([[15, 14], ...tips, [13, 22]], 'R');
      for (const [tx, ty] of tips) p.line(15, 14, tx, ty, 1, 'K');
      for (let k = 0; k < tips.length - 1; k++) {
        const [ax, ay] = tips[k], [bx, by] = tips[k + 1];
        p.line(ax, ay, (ax + bx) / 2 + 2, (ay + by) / 2 + 1, 1, 'K');            // σκαλωτή άκρη
      }
      // Ρούχο: φαρδαίνει προς τα κάτω, κουρελιασμένο.
      const hem = [];
      for (let x = 11; x <= 17; x += 2) hem.push([x, 40 + ((x + f) % 4 === 1 ? 1 : 0)]);
      p.poly([[14, 15], [18, 15], [18, 40], ...hem.reverse(), [10, 38]], 'K');
      for (const x of [12, 15]) p.line(x, 22, x - 1, 38, 1, 'k');                 // πτυχές
      // Μπράτσο με νύχια.
      p.line(14, 16, 10, 24, 2, 'P');
      p.line(10, 24, 9, 28, 1, 'P');
      p.px(8, 29, 'i'); p.px(9, 30, 'i'); p.px(10, 29, 'i');
      // Στήθος / λαιμός, ζώνη.
      p.poly([[15, 12], [18, 12], [18, 18], [14, 18]], 'P');
      p.line(14, 23, 18, 23, 1, 'Y');
      // Κεφάλι: χλωμό, βυθισμένα μάγουλα.
      p.ellipse(17.5, 8, 4, 4.6, 'P');
      p.px(15, 10, 'S'); p.px(15, 11, 'S');
      // Φίδια στα μαλλιά (αριστερά, μετά καθρέφτισμα).
      const snakes = [[16, 4, 12, 0], [14, 5, 8, 2], [14, 8, 9, 7], [17, 3, 16, 0]];
      snakes.forEach(([x0, y0, x1, y1], i) => {
        p.line(x0, y0, (x0 + x1) / 2 - 1, (y0 + y1) / 2 + (i % 2 ? 1 : -1), 1, 'g');
        p.line((x0 + x1) / 2 - 1, (y0 + y1) / 2 + (i % 2 ? 1 : -1), x1, y1, 1, 'G');
        p.px(x1, y1, 'g'); p.px(x1 - 1, y1, 't');
      });
      // Μάτια (κίτρινα, λάμπουν), φρύδια, στόμα.
      p.px(16, 8, 'y'); p.line(15, 7, 17, 6.5, 1, 'N');
      p.mirror();
      p.line(16, 11.5, 19, 11.5, 1, 'R');   // στόμα (κέντρο)
      p.px(17, 12, 'i'); p.px(18, 12, 'i');
    });
  },

  // ---- Χάροντας: γέρος βαρκάρης με κουκούλα, γκρίζα γένια, κουπί. f = 1: απλώνει την παλάμη.
  charon(f) {
    return paintGrid(30, 44, (p) => {
      // Κουπί (πίσω από το σώμα).
      p.line(25, 0, 19, 43, 2, 'o');
      p.line(26, 0, 20, 43, 1, 'O');
      p.poly([[17, 37], [22, 37], [21, 43], [17, 43]], 'o');
      // Ράσο.
      p.poly([[7, 15], [19, 15], [22, 40], [4, 40]], 'z');
      for (const x of [8, 12, 16]) p.line(x, 20, x - 1 + (x > 12 ? 2 : 0), 39, 1, 'Z');
      p.line(7, 25, 19, 25, 1, 'o');            // σχοινί στη μέση
      p.px(9, 26, 'o'); p.px(9, 27, 'O');
      // Πόδια / σανδάλια.
      p.poly([[7, 40], [11, 40], [11, 43], [6, 43]], 'b');
      p.poly([[14, 40], [18, 40], [19, 43], [14, 43]], 'b');
      // Κουκούλα και πρόσωπο.
      p.ellipse(13, 8, 7, 7.5, 'Z');
      p.ellipse(15, 9, 4, 4.6, 'T');
      p.px(16, 8, 'e'); p.line(14, 7, 17, 7, 1, 'U');      // μάτι, φρύδι
      p.px(18.5, 10, 'U');                                  // μύτη
      // Γένια.
      p.poly([[12, 11], [19, 11], [18, 20], [15, 23], [12, 18]], 'B');
      for (const x of [13, 15, 17]) p.line(x, 13, x, 20, 1, 'W');
      // Χέρι που κρατάει το κουπί.
      p.line(17, 17, 22, 22, 3, 'z');
      p.ellipse(22.5, 22.5, 1.6, 1.6, 'T');
      // Το άλλο χέρι: κρεμασμένο, ή απλωμένο μπροστά με την παλάμη ανοιχτή (ζητάει τον οβολό).
      if (f) {
        p.line(11, 17, 25, 25, 3, 'z');
        p.poly([[25, 23], [28, 23], [29, 25], [25, 27]], 'T');
        p.px(29, 23, 'T'); p.px(29, 24, 'U');
      } else {
        p.line(9, 17, 7, 28, 3, 'z');
        p.ellipse(7, 29, 1.5, 1.5, 'T');
      }
    });
  },

  // Η βάρκα: ξύλινη, με σανίδες, υψωμένη πλώρη και "μάτι" (όπως τα πλοία στα αγγεία).
  boat() {
    return paintGrid(54, 15, (p) => {
      p.poly([[0, 5], [53, 5], [48, 14], [6, 14]], 'o');
      p.poly([[48, 0], [53, 0], [53, 6], [47, 6]], 'o');          // πλώρη
      p.poly([[0, 2], [4, 2], [5, 6], [0, 6]], 'o');                // πρύμνη
      for (const y of [8, 11]) p.line(4, y, 49, y, 1, 'O');
      p.line(0, 5, 53, 5, 1, 'O');
      p.line(6, 13, 48, 13, 1, 'N');
      p.ellipse(45, 8, 2.3, 1.5, 'E'); p.px(45, 8, 'N');           // μάτι
      for (let x = 10; x <= 40; x += 10) p.line(x, 6, x, 12, 1, 'O');
    });
  },

  // Πέτρινος θρόνος με σκαλίσματα (για τον Άδη και την Περσεφόνη).
  throne(p) {
    p.poly([[4, 3], [33, 3], [33, 45], [4, 45]], 'm');
    p.poly([[8, 7], [29, 7], [29, 30], [8, 30]], 'M');
    for (let x = 9; x <= 27; x += 4) { p.line(x, 8, x + 2, 8, 1, 'n'); p.line(x + 2, 8, x + 2, 10, 1, 'n'); }   // μαίανδρος
    p.poly([[3, 0], [6, 0], [6, 4], [3, 4]], 'n'); p.poly([[31, 0], [34, 0], [34, 4], [31, 4]], 'n');      // κορυφές
    p.poly([[1, 26], [8, 26], [8, 33], [1, 33]], 'n'); p.poly([[29, 26], [36, 26], [36, 33], [29, 33]], 'n'); // μπράτσα
    p.poly([[6, 31], [31, 31], [31, 35], [6, 35]], 'n');                                                   // κάθισμα
    p.poly([[2, 43], [35, 43], [35, 47], [2, 47]], 'M');                                                   // βάθρο
    p.line(2, 43, 35, 43, 1, 'n');
  },

  // ---- Άδης: στον θρόνο, σκούρα πανοπλία, κόκκινη κάπα, μαύρα γένια, σκοτεινό στέμμα με χρυσές
  // αιχμές, δίκρανο. Από μπροστά.
  hades() {
    return paintGrid(38, 48, (p) => {
      this.throne(p);
      p.poly([[11, 13], [26, 13], [29, 41], [8, 41]], 'R');                 // κάπα
      p.poly([[13, 13], [24, 13], [23, 29], [14, 29]], 'k');                // πανοπλία
      for (const y of [17, 21, 25]) p.line(14, y, 23, y, 1, 'K');
      p.line(18.5, 14, 18.5, 28, 1, 'K');
      p.line(13, 13, 24, 13, 1, 'Y');                                         // χρυσό τελείωμα
      p.poly([[13, 29], [24, 29], [24, 39], [13, 39]], 'K');                // πόδια
      p.line(18.5, 30, 18.5, 39, 1, 'k');
      p.poly([[13, 39], [17, 39], [17, 42], [12, 42]], 'b'); p.poly([[20, 39], [24, 39], [25, 42], [20, 42]], 'b');
      // Κεφάλι, γένια, μάτια που λάμπουν κόκκινα, στέμμα.
      p.ellipse(18.5, 8.5, 3.8, 4.2, 's');
      p.poly([[14.5, 9.5], [22.5, 9.5], [21, 17], [18.5, 18], [16, 17]], 'K');
      p.px(17, 8, 'r'); p.px(20, 8, 'r'); p.line(16, 6.5, 21, 6.5, 1, 'K');
      p.line(14, 4.5, 23, 4.5, 2, 'K');
      for (const [x, y] of [[14, 3], [16, 1], [18.5, 0], [21, 1], [23, 3]]) p.line(x, 4, x, y, 1, 'Y');
      // Δίκρανο στο δεξί χέρι, το άλλο χέρι στο μπράτσο του θρόνου.
      p.line(30, 2, 30, 42, 1, 'Y');
      p.line(29, 0, 29, 4, 1, 'y'); p.line(31, 0, 31, 4, 1, 'y'); p.line(29, 4, 31, 4, 1, 'Y');
      p.line(24, 18, 29, 23, 2, 'k'); p.ellipse(29.5, 23, 1.5, 1.5, 's');
      p.line(13, 18, 8, 27, 2, 'k'); p.ellipse(7.5, 27.5, 1.5, 1.5, 's');
    });
  },

  // ---- Περσεφόνη: στον θρόνο, λευκό φόρεμα, σκούρα μαλλιά, στέμμα με ρόδι, ρόδι στα χέρια.
  // f = 1: γέρνει προς τον Άδη (το κεφάλι λίγο αριστερά).
  persephone(f) {
    return paintGrid(38, 48, (p) => {
      this.throne(p);
      const hx = f ? 17.5 : 18.5;
      p.ellipse(hx, 10, 5, 6, 'a');                                          // μαλλιά (πίσω)
      p.poly([[13, 13], [24, 13], [27, 42], [10, 42]], 'w');                // φόρεμα
      for (const x of [14, 18, 22]) p.line(x, 22, x + (x - 18) * 0.25, 41, 1, 'W');
      p.line(13, 21, 24, 21, 1, 'y');                                         // ζώνη
      p.poly([[13, 13], [16, 13], [15, 20], [12, 18]], 'a');                // μαλλιά στους ώμους
      p.poly([[21, 13], [24, 13], [25, 18], [22, 20]], 'a');
      p.ellipse(hx, 9, 3.3, 4, 's');                                         // πρόσωπο
      p.px(hx - 1.3, 9, 'e'); p.px(hx + 1.3, 9, 'e'); p.px(hx, 11.5, 'r');
      p.line(hx - 3.5, 4.5, hx + 3.5, 4.5, 1, 'y');                          // στέμμα
      p.ellipse(hx, 2.5, 1.6, 1.4, 'r'); p.px(hx, 1, 'R');                  // ρόδι στο στέμμα
      p.line(13, 15, 16, 25, 2, 'w'); p.line(24, 15, 21, 25, 2, 'w');        // μπράτσα
      p.ellipse(18.5, 26, 2, 1.7, 'r'); p.px(18.5, 25, 'R');               // ρόδι στα χέρια
      p.px(16, 26, 's'); p.px(21, 26, 's');
    });
  },

  // ---- Ευρυδίκη: χλωμό φάσμα γυναίκας, μακριά μαλλιά που ανεμίζουν πίσω, φόρεμα που σβήνει
  // προς τα κάτω (σαν να μην πατάει στη γη). 3 καρέ βαδίσματος.
  eurydice(f) {
    return paintGrid(28, 44, (p) => {
      const sw = [0, 1, -1][f];
      p.poly([[7, 4], [13, 2], [14, 9], [10, 20], [5 - sw, 19], [6, 11]], 'c');          // μαλλιά
      p.poly([[9, 12], [17, 12], [22 + sw, 40], [4 - sw, 40]], 'p');                     // φόρεμα
      for (const x of [9, 13, 17]) p.line(x, 18, x + (x - 13) * 0.4 + sw, 39, 1, 'P');
      p.line(9, 19, 17, 19, 1, 'P');
      p.ellipse(14, 7, 3.4, 4, 'p');                                                     // πρόσωπο
      p.px(15.5, 7, 'v'); p.line(15, 6, 16.5, 6, 1, 'P'); p.px(16, 9.5, 'P');
      p.line(16, 14, 21, 21 + sw, 2, 'p'); p.ellipse(21.5, 22 + sw, 1.3, 1.3, 'p');       // χέρι μπροστά
      p.line(10, 14, 8, 23, 2, 'p');
      // Ο ποδόγυρος "σβήνει": κάθε δεύτερο pixel διάφανο στις τελευταίες γραμμές.
      p.map((x, y, ch) => (y >= 36 && ch !== '.' && (x + y) % 2 ? '.' : ch));
    });
  },

  // ---- Χαμένες ψυχές: φασματικές μορφές με ουρά αντί για πόδια, θλιμμένο ανοιχτό στόμα.
  // kind: 'm' (άντρας, κοντά μαλλιά), 'f' (γυναίκα, μακριά μαλλιά), 'old' (γέρος, γένια, σκυφτός).
  soul(kind, f) {
    return paintGrid(22, 32, (p) => {
      const old = kind === 'old', hx = old ? 12 : 11, hy = old ? 7 : 6;
      if (kind === 'f') p.poly([[6, 3], [16, 3], [17, 15], [5, 15]], 'c');               // μαλλιά (πίσω)
      p.poly([[6, 10], [16, 10], [14, 22], [11 + f, 31], [8, 22]], 'p');                 // σώμα-ουρά
      for (const x of [8, 11, 14]) p.line(x, 13, x - (x - 11) * 0.3, 22, 1, 'P');
      p.line(6, 11, 3, 19 + f, 1, 'p'); p.line(16, 11, 19, 19 - f, 1, 'p');               // χέρια
      p.ellipse(hx, hy, 3.3, 3.8, 'p');
      if (kind === 'm') p.line(hx - 3, hy - 3, hx + 3, hy - 3, 1, 'P');
      if (old) { p.poly([[hx - 2, hy + 2], [hx + 3, hy + 2], [hx + 1, hy + 8], [hx - 1, hy + 7]], 'P'); p.line(hx - 3, hy - 3, hx + 2, hy - 4, 1, 'P'); }
      p.px(hx - 1.3, hy, 'v'); p.px(hx + 1.3, hy, 'v'); p.px(hx, hy + 2, 'v');           // μάτια, στόμα
      p.map((x, y, ch) => (y >= 27 && ch !== '.' && (x + y) % 2 ? '.' : ch));             // η ουρά σβήνει
    });
  },

  // ---- Φίδι: κουλουριασμένο, με λέπια (ρόμβοι). f = 1: σηκώνει το κεφάλι και σφυρίζει
  // (ανοιχτό στόμα, δόντια, διχαλωτή γλώσσα).
  snake(f) {
    return paintGrid(34, 22, (p) => {
      for (const [cy, rx, ry] of [[17, 12, 3.8], [13.5, 9, 3.2], [10.5, 6, 2.5]]) {
        p.ellipse(15, cy + 0.6, rx + 0.4, ry + 0.4, 'd');
        p.ellipse(15, cy, rx, ry, 'g');
      }
      // Λέπια: ρόμβοι σε πλέγμα.
      p.map((x, y, ch) => (ch === 'g' && (x + y * 2) % 5 === 0 ? 'G' : ch));
      if (f) {
        p.line(18, 10, 22, 6, 2, 'g'); p.line(22, 6, 24, 3, 2, 'g');
        p.ellipse(26, 2.5, 3.2, 2.2, 'g');
        p.px(26.5, 1.5, 'r');
        p.line(28, 3.5, 31, 3.5, 1, 't'); p.px(32, 3, 't'); p.px(32, 4, 't');
        p.px(28, 4.5, 'i');
      } else {
        p.ellipse(22, 9.5, 3.2, 1.9, 'g');
        p.px(23, 9, 'r');
        p.line(25, 10, 26, 10, 1, 't');
      }
    });
  },
};
